"""Compiled sprites (10 November 2026, experiment; build with NEM_CSPR=1).

Writes cspr_code.asm: drawing code for the ship's level frame (ship_pat in
ship.asm, the first 32 bytes) and Konami's round bullet (pattern 136, the
same in every stage: native/spr_common.bin from native_pack.py), one routine
per pixel offset 0-7, with a table of the eight addresses for each
(cs_ship_tab, cs_bul_tab, 16-byte aligned) for draw_sprite16's dispatch.

A routine is entered with HL = the screen address of the sprite's top line
at its first column (draw_sprite16's DE).  For each line down to the last
with pixels: for each non-zero byte of the line shifted right by the offset
(two bytes at offset 0, three otherwise, as draw_sprite16 draws them),
`ld a,(hl) / or n / ld (hl),a`, with `inc l` / `dec l` between columns;
then `inc h / ld a,h / and 7 / call z,cs_fix` to the next line, cs_fix
moving to the next character row as draw_sprite16's own step does."""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__))

def ship_level():
    src = open(os.path.join(HERE, 'ship.asm')).read()
    i = src.index('ship_pat:')
    vals = []
    for line in src[i:].split('\n')[1:]:
        m = re.match(r'\s*db\s+(.*)', line)
        if m: vals += [int(v.strip(), 16) for v in m.group(1).split(';')[0].split(',')]
        if len(vals) >= 32: break
    return bytes(vals[:32])

def routine(pat, sh):
    L, R = pat[:16], pat[16:32]
    rows = []
    for r in range(16):
        if sh == 0: rows.append([L[r], R[r]])
        else:
            v = (L[r] << 16 | R[r] << 8) >> sh
            rows.append([v >> 16 & 255, v >> 8 & 255, v & 255])
    last = max([r for r in range(16) if any(rows[r])], default=-1)
    out = []; col = 0
    for r in range(last + 1):
        for k, b in enumerate(rows[r]):
            if not b: continue
            while col < k: out.append('    inc l'); col += 1
            while col > k: out.append('    dec l'); col -= 1
            out += ['    ld a,(hl)', '    or 0x%02X' % b, '    ld (hl),a']
        if r < last:
            out += ['    inc h', '    ld a,h', '    and 7', '    call z,cs_fix']
    out.append('    ret')
    return out

common = open(os.path.join(HERE, 'native', 'spr_common.bin'), 'rb').read()
assert len(common) == 40 * 32, len(common)
pats = [('ship', ship_level()), ('bul', common[34 * 32:35 * 32])]
lines = ['; generated by cspr_gen.py: compiled sprites (NEM_CSPR=1)',
         'cs_fix:                         ; the next character row (as draw_sprite16)',
         '    ld a,l', '    add a,32', '    ld l,a', '    ret c', '    ld a,h', '    sub 8', '    ld h,a', '    ret']
for name, pat in pats:
    lines += ['    align 16', 'cs_%s_tab:' % name] + ['    dw cs_%s_%d' % (name, s) for s in range(8)]
for name, pat in pats:
    for s in range(8):
        lines += ['cs_%s_%d:' % (name, s)] + routine(pat, s)
open(os.path.join(HERE, 'cspr_code.asm'), 'w').write('\n'.join(lines) + '\n')
