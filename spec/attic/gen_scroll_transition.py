"""Write scroll_gen.asm: the scroll's column shift (MSX 4695-46A6) with the
map comparison folded in.

Konami moves each of the 22 map rows one cell left (columns 1-31 to 0-30).
When the shift starts, name_shadow equals Konami's map (nm_flush has just
taken the regions written so far this tick), so a cell changes exactly where
two neighbours in the old row differ.  An unchanged cell is neither written
nor compared with name_shadow: 29 T-states.  A changed one is written to
the map and name_shadow and marked in the group masks (B = changed,
IXH = now a star), which upl_group takes as the full comparison does.

Registers: HL = source (column x+1), DE = name_shadow at x+1, C = the old
value of column x (equal to the new value of x-1), IXL = group (cell >> 3)."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
out = []
w = out.append
w('; Generated by gen_scroll.py: do not edit.')
w('scroll_d:')
w('    ld a,(nm_full)')
w('    or a')
w('    jp nz,.plain')
w('    push bc')
w('    push ix')
w('    call nm_flush               ; name_shadow = the map, lists empty')
w('    ld hl,0xED00+KRAM')
w('    ld de,name_shadow')
w('    ld ix,0')
w('    ld b,0')
w('.row:')
w('    ld c,(hl)                   ; column 0 (old)')
w('    inc l')
w('    inc e')
diffs = []
for x in range(31):
    n = x & 7
    w('    ld a,(hl)')
    w('    cp c')
    w('    call nz,.d%d' % x)
    if x < 30:
        w('    inc l')
        w('    inc e')
    if n == 7 or x == 30:
        w('    ld a,b')
        w('    or a')
        w('    call nz,.group')
        w('    inc ixl')
    diffs.append(x)
w('    inc hl                      ; to column 0 of the next row (may cross a page)')
w('    inc de')
w('    ld a,ixl')
w('    cp 88')
w('    jp nz,.row')
w('    pop ix')
w('    pop bc')
w('    ret')
w('.group:                         ; B changed cells, IXH stars: as upl_group')
w('    push bc')
w('    ld c,b')
w('    ld b,ixh')
w('    call upl_group')
w('    pop bc')
w('    ld b,0')
w('    ld ixh,b')
w('    ret')
for x in diffs:
    n = x & 7
    w('.d%d:' % x)
    w('    ld c,a')
    w('    dec l')
    w('    ld (hl),a')
    w('    inc l')
    w('    dec e')
    w('    ld (de),a')
    w('    inc e')
    w('    set %d,b' % n)
    w('    sub 0xf6')
    w('    cp 2')
    w('    ret nc')
    w('    ld a,ixh')
    w('    or %d' % (1 << n))
    w('    ld ixh,a')
    w('    ret')
w('.plain:                         ; a full comparison is due anyway: plain shift')
w('    ld hl,0xED01+KRAM')
w('    ld de,0xED00+KRAM')
w('    ld b,22')
w('.prow:')
w('    push bc')
w('    ld bc,31')
w('    ldir')
w('    pop bc')
w('    inc hl')
w('    inc de')
w('    djnz .prow')
w('    ret')
open(os.path.join(HERE, 'scroll_gen.asm'), 'w').write('\n'.join(out) + '\n')
