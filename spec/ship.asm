; The ship (Vic Viper), redrawn for the Spectrum (0.100).  On the MSX it is
; two hardware sprites at the same place, Konami's patterns 0/4 (level),
; 8/12 (diving) and 16/20 (climbing): white, with a red canopy (a light blue
; belly when climbing) as a second one-colour sprite.  Here a cell has one
; ink, so the second sprite only cost a draw and an erase; it is not drawn,
; and the white one is drawn from these patterns instead of Konami's
; (0.105): Konami's outline, with the second colour shown in one colour.
; Level and diving: the red canopy as a black line inside the ship's white
; outline (the top edge of the canopy white, the line beneath it).
; Climbing: the light blue belly as a checkerboard stipple under the solid
; white top.
;
; spr_patsel: A = a sprite's pattern number (a multiple of 4).  Returns HL =
; its 32 bytes (TMS layout: left column rows 0-15, then the right column)
; with carry clear, or carry set for a sprite not to draw.  Clobbers DE.
spr_patsel:
    cp 24
    jr nc,.konami
    bit 2,a
    scf
    ret nz                      ; 4, 12, 20: the ship's second colour
    add a,a
    add a,a                     ; 0, 8, 16 -> 0, 32, 64
    ld l,a
    ld h,0
    ld de,ship_pat
    add hl,de                   ; (no carry)
    ret
.konami:
    ld l,a
    ld h,0
    add hl,hl
    add hl,hl
    add hl,hl
    ld de,SPR_PAT
    add hl,de                   ; (no carry: at most FFE0)
    ret

    ifdef Z48                   ; (the 48K's layout moves: ship_pat must not cross a page)
    if ($ & 0xff) > 0xA0
    align 256
    endif
    endif
    align 32                    ; draw_sprite16 and spr_edge step rows by L
ship_pat:
; level (pattern 0)
;   #...............
;   ###.............
;   .###............
;   .##########.....
;   .#######...##...
;   #.##############
;   #.###########...
;   #.######........
;   .####...........
;   ###.............
    db 0x00,0x80,0xE0,0x70,0x7F,0x7F,0xBF,0xBF,0xBF,0x78,0xE0,0x00,0x00,0x00,0x00,0x00
    db 0x00,0x00,0x00,0x00,0xE0,0x18,0xFF,0xF8,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00
; diving (pattern 8)
;   #.##............
;   ######..........
;   .##########.....
;   .#######...##...
;   #.##############
;   #.############..
;   #.#########.....
;   .#######........
;   .####...........
;   ###.............
    db 0x00,0x00,0x00,0xB0,0xFC,0x7F,0x7F,0xBF,0xBF,0xBF,0x7F,0x78,0xE0,0x00,0x00,0x00
    db 0x00,0x00,0x00,0x00,0x00,0xE0,0x18,0xFF,0xFC,0xE0,0x00,0x00,0x00,0x00,0x00,0x00
; climbing (pattern 16)
;   #...............
;   ###.............
;   .###............
;   #########.......
;   #.##########....
;   .#.#.#.#########
;   ..#.#.#.#.#.#...
;   ...#.#.#.#.#....
;   ....#.#.........
;   ...#............
    db 0x00,0x80,0xE0,0x70,0xFF,0xBF,0x55,0x2A,0x15,0x0A,0x10,0x00,0x00,0x00,0x00,0x00
    db 0x00,0x00,0x00,0x00,0x80,0xF0,0xFF,0xA8,0x50,0x00,0x00,0x00,0x00,0x00,0x00,0x00
