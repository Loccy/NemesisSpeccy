"""Build one stage's image of the 48K version (spec/release48.sh builds all
eight and the tapes).

With Z48_SHARED=1 (the release): the core (5B00-AEFF and C000 up to C400)
is the same in every image, and the stage's block (C400-FFFF) holds what
only that stage needs.  Konami's code is relocated by reloc/gen.py with
NEM_Z48=1 and the stage's keep list (reloc/z48_keepc_N.txt, from
tools/z48/keepC.py); the platform is assembled with Z48 defined; the data
come from z48_data.py.  Z48_STAGE=N picks the stage (nemesis48h.sna for
stage 1, nemesis48_sNh.sna for the others); Z48_CHEAT=1 makes the test
build (the names end in hc).  The layout search's answers are kept in
z48_fitcache.json."""
import os, re, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__))
RELOC = os.path.join(HERE, '..', 'reloc')
sys.path.insert(0, HERE)
from build import run, check_inputs

SP = 0xBFF0                                       # (the snapshot's stack: Konami's)
STAGE = int(os.environ.get('Z48_STAGE', '1'))      # the multiload: which stage's image
LAST = int(os.environ.get('Z48_LAST', '8'))         # the last stage before THE END
NOBC = os.environ.get('Z48_NOBC') == '1'       # the preview: no Big Core characters
DEFS = ['-DZ48=1', '-DADAPT=1', '-DPACE_T=15', '-DPACE_SLACK=8', '-DLOGIC_EXTRA=0', '-DFRAMES_PER_TICK=1',
        '-DTRIM=1', '-DINPUT_DRAW', '-DLAST48=%d' % LAST] + (['-DZ48_NOBC=1'] if NOBC else [])
CHEAT = os.environ.get('Z48_CHEAT') == '1'
SHARED = os.environ.get('Z48_SHARED') == '1'   # the shared layout: the core, and the stage's block from OV48
if SHARED: DEFS.append('-DZ48SH=1')
OV48 = 0xC000     # the test build: invulnerable, powered up each life
if CHEAT: DEFS.append('-DZ48_CHEAT=1')
for _d in ('Z48_SYNC_LOGIC', 'Z48_ROWS'):              # (trials, off)
    if os.environ.get(_d) == '1': DEFS.append('-D%s=1' % _d)
if os.environ.get('Z48_VSYNC') == '1': DEFS.append('-DZ48_VSYNC=1')   # (trial, off: preview 5, declined)
if os.environ.get('Z48_TWOPASS') == '1': DEFS.append('-DZ48_TWOPASS=1')   # (comparison: the old drawing order)

def symbols(path):
    out = {}
    for line in open(path):
        p = line.split()
        if len(p) >= 3 and p[1] == 'EQU':
            out[p[0].rstrip(':')] = int(p[2], 16) & 0xFFFF
    return out

def gen(split=''):
    env = dict(os.environ, NEM_TARGET='spec', NEM_Z48='1', NEM_Z48_SPLIT=split, NEM_Z48_STAGE=str(STAGE),
               NEM_Z48_SHARED='1' if SHARED else '')
    out = run([sys.executable, 'gen.py'], RELOC, env)
    if 'True' not in out.split('\n')[0]:
        sys.exit('identity check failed:\n' + out)

def main():
    check_inputs()
    gen()
    run([sys.executable, 'tables.py'], HERE, dict(os.environ, NEM_Z48='1'))
    run([sys.executable, 'gen_fullcmp.py'], HERE)
    print(run([sys.executable, 'z48_data.py'], HERE, dict(os.environ, Z48_STAGE=str(STAGE))).strip())
    print(run([sys.executable, 'z48_sfx.py'], HERE).strip())
    open(os.path.join(HERE, 'z48_hplace.asm'), 'w').write('; generated by build48.py (the coverage build: none)\n')
    # 1. bank 2 whole, under 3C00 (the coverage build): its items measured
    run(['sjasmplus', '--nologo', '--msg=war', '--sym=cov48.sym', '--lst=cov48.lst'] + DEFS
        + ['-DZ48COV=1', '-DA2_ORG=0x1000', '-DDATA48=0x2000', '-DOV48=0x2800', 'plat_spec.asm'], HERE)
    c = symbols(os.path.join(HERE, 'cov48.sym'))
    # the platform's alignment gaps (8000 up): each `align 256` that pads
    pads = []
    for line in open(os.path.join(HERE, 'cov48.lst'), errors='replace'):
        m = re.match(r'\s*\d+\+*\s+([0-9A-F]{4})\s+(?:[0-9A-F]{2} ?)+(?:\.\.\.)?\s+align 256', line)
        if m:
            a = int(m.group(1), 16)
            if 0x8000 <= a < c['page_d_end'] and (-a) % 256 >= 24: pads.append((a, (a + 255) & ~255))
    reserve = 0 if SHARED else int(os.environ.get('Z48_RESERVE', {2: '1700'}.get(STAGE, '1300')))   # left at A2's end for the data (stage 2's map is longer)
    regions = [(c['page_d_end'], 0xAD00 - reserve), (c['low_end'], 0x8000), (c['native_end'], 0x7B40),
               (c['page_7_end'], 0xF800), (0xAE01, 0xAEAE), (0xAEB1, 0xAEFD), (0xF300, 0xF600)] + pads   # (BF01-BF7F, AEFD-AEFF: the multiload)
    high = []
    if SHARED:      # the shared layout: the areas inside the stage's block hold the stage's own data, not the core
        high = [r for r in regions if r[0] >= 0xC000]
        regions = [r for r in regions if r[0] < 0xC000]
    regions = [regions[0]] + sorted(regions[1:], key=lambda r: r[0] - r[1])
    global OV48
    def orders(extra):               # the C000 area in each place in the order (the cutter fills in order)
        if not extra: return [regions]
        return [regions[:k] + [(0xC000, 0xC000 + extra)] + regions[k:] for k in range(1, len(regions) + 1)]
    def fit(rg):
        env = dict(os.environ, Z48_REGIONS=','.join('%04X-%04X' % r for r in rg), NEM_Z48_STAGE=str(STAGE),
                   NEM_Z48_SHARED='1' if SHARED else '', Z48_FIT_BANKS='1,2' if SHARED else '2')
        return subprocess.run([sys.executable, 'fit48.py', os.path.join(HERE, 'cov48.sym')], cwd=HERE, env=env, capture_output=True, text=True)
    def fits(extra):                 # the first order that fits, or None
        for rg in orders(extra):
            p = fit(rg)
            if p.returncode == 0: return rg, p
        return None
    # the search is the same for every image whose core is the same (all
    # sixteen, as a rule): its answer is kept, by the inputs fit48.py uses
    # (the core's items and their sizes, the cut rules, the margin, the
    # areas), in z48_fitcache.json
    import json, hashlib
    cachef = os.path.join(HERE, 'z48_fitcache.json')
    try: cache = json.load(open(cachef))
    except (OSError, ValueError): cache = {}
    kp = subprocess.run([sys.executable, 'fit48.py', os.path.join(HERE, 'cov48.sym')], cwd=HERE, capture_output=True, text=True,
                        env=dict(os.environ, Z48_FIT_KEY='1', Z48_REGIONS=','.join('%04X-%04X' % r for r in regions),
                                 NEM_Z48_STAGE=str(STAGE), NEM_Z48_SHARED='1' if SHARED else '', Z48_FIT_BANKS='1,2' if SHARED else '2'))
    key = hashlib.md5((kp.stdout.strip() + repr(regions) + str(SHARED)).encode()).hexdigest() if kp.returncode == 0 else None
    extra = None
    if key in cache:
        extra = cache[key]; print('the core\'s layout: as before (z48_fitcache.json)')
    elif SHARED:                     # the smallest C000 area: in 256s, then back down in 16s
        for e in range(0, 0x1A00, 0x100):
            if fits(e): break
        for f in range(max(0, e - 0xF0), e, 0x10):
            if fits(f): e = f; break
        extra = e
    else:
        extra = 0
    # the shared layout: what the core cannot fit below goes at C000, and
    # the stage's block starts after it (OV48)
    r = fits(extra)
    if not r:
        p = fit(regions + ([(0xC000, 0xC000 + extra)] if extra else []))
        sys.exit('FAILED: fit48.py\n' + p.stdout + p.stderr)
    rg, p = r
    if key and cache.get(key) != extra:
        cache[key] = extra; json.dump(cache, open(cachef, 'w'))
    if SHARED:
        OV48 = 0xC000 + extra; print('the stage\'s block from %04X' % OV48)
    regions = rg
    split = p.stdout.strip().split('\n')[-1]
    if split.startswith('#'): split = ''
    print('cut:', split or '(none)')
    # the Big Core's packed sets: in what the regions have left, largest first
    held = [tuple(int(x, 16) for x in l.split()[:2]) + (int(l.split()[2]),) for l in open(os.path.join(HERE, 'z48_held.txt'))]
    room0 = [[st + h, 0xAD00 if k == 0 else lim] for k, (st, lim, h) in enumerate(held)] + [[(c['section_A_end'] + 15) & ~15, 0xD9EE]]   # (to bank 5's shapes)
    place = []
    if os.path.exists(os.path.join(HERE, 'z48_sizes.txt')) and not SHARED:
        blobs = [(l.split()[0], int(l.split()[1])) for l in open(os.path.join(HERE, 'z48_sizes.txt')) if l.strip()]
        for pick in ((max,) if os.environ.get('Z48_WORSTFIT') else (min, max)):   # largest first, best fit; else worst fit
            room = [r[:] for r in room0]; place = []
            for nm, n in sorted(blobs, key=lambda x: -x[1]):
                r = pick((r for r in room if r[1] - r[0] >= n), key=lambda r: r[1] - r[0], default=None)
                if r is None: break
                place.append((nm, r[0], n)); r[0] += n
            else:
                print('data placed; left: %d bytes in %s' % (sum(b - a for a, b in room), ' '.join('%04X+%d' % (a, b - a) for a, b in room)))
                break
        else:
            sys.exit('no room for %s (%d bytes); left: %s' % (nm, n, ' '.join('%04X+%d' % (a, b - a) for a, b in room)))
    hp = []
    if SHARED:      # the stage's own data in the high areas, largest first, best fit
        blobs = [(l.split()[0], int(l.split()[1])) for l in open(os.path.join(HERE, 'z48_sizes.txt')) if l.strip()]
        blobs = [b for b in blobs if b[0] not in ('map48_pieces', 'map48_tword')]
        room = [list(r) for r in high]
        for nm, n in sorted(blobs, key=lambda x: -x[1]):
            r = min((r for r in room if r[1] - r[0] >= n), key=lambda r: r[1] - r[0], default=None)
            if r is None: continue
            hp.append((nm, r[0], n)); r[0] += n
        print('stage data in the high areas: %d bytes (%s); left there %d' % (sum(n for _, _, n in hp), ' '.join(nm for nm, _, _ in hp), sum(b - a for a, b in room)))
        tf = [l.strip() for l in open(os.path.join(HERE, 'z48_tilefree.txt')) if l.strip()]     # (and in the tile store's unused numbers)
        os.environ['Z48_HIGH_FREE'] = '' if os.environ.get('Z48_NO_OVHIGH') else ','.join(['%04X-%04X' % (a, b) for a, b in room if b > a] + ([] if os.environ.get('Z48_NO_TILEFREE') else tf))   # (gen.py: the stage's own tables there)
    open(os.path.join(HERE, 'z48_hplace.asm'), 'w').write('; generated by build48.py\n' + ''.join('    define HPLACE_%s 0x%04X\n' % (nm, a) for nm, a, n in hp))
    with open(os.path.join(HERE, 'z48_layout.asm'), 'a') as f:
        if place: f.write('    define Z48_PLACED\n')
        for nm, a, n in place:
            f.write('    macro z48_place_%s\n        org 0x%04X\n    endm\n' % (nm, a))
            print('%s at %04X-%04X' % (nm, a, a + n - 1))
    # 2. the 48K map
    gen(split)
    data48 = (c['section_A_end'] + 15) & ~15
    name = ('nemesis48' if STAGE == 1 else 'nemesis48_s%d' % STAGE) + ('h' if SHARED else '') + ('c' if CHEAT else '')
    log = run(['sjasmplus', '--nologo', '--msg=war', '--sym=%s.sym' % name, '--lst=%s.lst' % name] + DEFS
              + ['-DDATA48=0x%04X' % data48, '-DOV48=0x%04X' % OV48, '-DOUT48="%s.mem"' % name, 'plat_spec.asm'], HERE)
    if log.strip():
        print(log)
    syms = symbols(os.path.join(HERE, name + '.sym'))
    for k in ('section_fixed_end', 'section_C_end', 'native_end', 'section_A_end', 'map48_end', 'platform_end',
              'hot_end', 'page_d_end', 'section_A2_end'):
        if k in syms: print('%-20s %04X' % (k, syms[k] & 0xFFFF))
    mem = bytearray(open(os.path.join(HERE, name + '.mem'), 'rb').read())
    assert len(mem) == 0xC000
    if CHEAT:
        mem[syms['m1_75F0'] - 0x4000] = 0xC9      # la_nave_ha_muerto: a bare ret
    pc = syms['plat_boot']
    sp = SP - 2
    mem[sp - 0x4000] = pc & 255; mem[sp - 0x4000 + 1] = pc >> 8
    # 48K .sna: I, HL', DE', BC', AF', HL, DE, BC, IY, IX, IFF2, R, AF, SP, IM, border; then 4000-FFFF
    hdr = bytes([0x3F]) + bytes(18) + bytes([0, 0]) + bytes([0, 0]) + sp.to_bytes(2, 'little') + bytes([1, 0])
    assert len(hdr) == 27
    open(os.path.join(HERE, name + '.sna'), 'wb').write(hdr + mem)
    print(name + '.sna written')

if __name__ == '__main__':
    if SHARED and 'Z48_MARGIN' not in os.environ:
        for mg in (6, 12, 20, 32, 48):        # (jr made jp across a cut: a little room at each area's end)
            p = subprocess.run([sys.executable] + sys.argv, env=dict(os.environ, Z48_MARGIN=str(mg)), capture_output=True, text=True)
            if p.returncode == 0:
                print(p.stdout, end=''); print('(margin %d)' % mg); break
            last = p.stdout + p.stderr
            if 'z48_layout_check' not in last: break
        else:
            pass
        if p.returncode: sys.exit(last)
    elif 'Z48_RESERVE' in os.environ or SHARED:
        main()
    else:                                   # the room kept for data: the first that fits
        base = 0 if SHARED else {2: 1700}.get(STAGE, 1300)
        for r in [base] + [base + d for k in range(1, 7) for d in (-50 * k, 50 * k)]:
            p = subprocess.run([sys.executable] + sys.argv, env=dict(os.environ, Z48_RESERVE=str(r)), capture_output=True, text=True)
            if p.returncode == 0:
                print(p.stdout, end=''); print('(data reserve %d)' % r); break
            last = p.stdout + p.stderr
        else:
            sys.exit(last)
