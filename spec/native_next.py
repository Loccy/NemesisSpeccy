"""The Spectrum Next's native graphics (claude/native-128k-plan.md, step 3):
Konami's graphics loads other than the stage loads, as the bytes they wrote
(native_sets.next_events), for native.asm's Next loads into the Next's own
store of character rows (pages C and D, E800) and sprite patterns (bank 7,
F800).  Writes native_next.dat (8K pages NX_PAGE on, raw: nx_pack.py puts
it in the .NEX) and native_tables_next.asm (their descriptors; built with
NEM_NEXT=1).  The stage loads come from the Next's stage files, which
nx_pack.py completes with Konami's own bytes (stage_files()).

Pieces (each within one 8K page, read at 4000):
  colours, patterns  a 96-byte mask (bit k: character third * 256 + char),
                     then the 8 bytes of each marked character in order
  sprite patterns    an 8-byte mask, then the 32 bytes of each marked one
A descriptor: the page (FF: none), then the address at 4000.  An event:
three descriptors (colours, patterns, sprite patterns).
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import native_sets

NX_PAGE = 84                    # banks 42-45 (nx_pack.py: free there)
NX_PAGES = 8
GFX = os.path.join(HERE, 'nxgfx')

def rom_patch():
    """The MSX2 patch's data changes (nxgfx/patches.txt: MSX bank, address,
    old, new): Konami's loaders on the Next read them (the font and its
    colours, in code the native build leaves out, among them), so the
    replays run on a ROM with them in; enh_patch.py applies the rest to
    the .NEX."""
    out = []
    for l in open(os.path.join(GFX, 'patches.txt')):
        l = l.split('#')[0].split()
        if l:
            b, a, old, new = int(l[0]), int(l[1], 16), int(l[2], 16), int(l[3], 16)
            out.append(((b << 13) | (a & 0x1FFF), old, new))
    return out
native_sets.ROM_PATCH = rom_patch()

def piece(d, nmask, size):
    mask = bytearray(nmask)
    for k in d: mask[k >> 3] |= 1 << (k & 7)
    out = bytes(mask) + b''.join(d[k] for k in sorted(d))
    assert len(out) == nmask + size * len(d)
    return out

def stage_files():
    """The Next's stage files completed with Konami's own stage loads: every
    byte of 0000-37FF the file's mask (3900, a bit a byte) leaves out is what
    Konami's load writes there, or else what the stage before it in play
    left (never shown: the census), so lo_apply copies them whole.
    -> {1-8: 16K, 'bonus': 16K (stage 9's load)}, and for stages 10-12 the
    characters whose colours Konami's load gives otherwise (as {char: 8
    bytes}; outside the bonus file's mask: checked)."""
    out = {}; fix = {}
    def bake(f, vw, prev):
        v, w = vw
        f = bytearray(f); m = f[0x3900:0x4000]
        for a in range(0x3800):
            if (m[a >> 3] >> (a & 7)) & 1: continue
            f[a] = v[a] if a in w or prev is None else prev[a]
        return bytes(f)
    # bytes neither the patch nor Konami's load writes keep what the stage
    # before it in play left, as on the Next before (never shown: the census)
    for n in range(1, 9):
        f = open(os.path.join(GFX, 'stage%d.bin' % n), 'rb').read()
        out[n] = bake(f, native_sets.stage_vram(n), out.get(n - 1))
    f = open(os.path.join(GFX, 'bonus.bin'), 'rb').read(); m = f[0x3900:0x4000]
    v9, w9 = native_sets.stage_vram(9)
    out['bonus'] = bake(f, (v9, w9), out[2])
    for n in (10, 11, 12):
        v, w = native_sets.stage_vram(n)
        d = sorted(a for a in w if v[a] != v9[a])
        assert all(a < 0x1800 and not (m[a >> 3] >> (a & 7)) & 1 for a in d), 'bonus stage %d: not colours outside the mask' % n
        fix[n] = {k: bytes(v[k * 8:k * 8 + 8]) for k in sorted(set(a >> 3 for a in d))}
    return out, fix

def main():
    ev = native_sets.next_events()
    pages = [bytearray() for _ in range(NX_PAGES)]
    where = {}
    def place(data):
        if data in where: return where[data]
        for i, p in enumerate(pages):
            if len(p) + len(data) <= 0x2000:
                where[data] = (NX_PAGE + i, 0x4000 + len(p)); p += data; return where[data]
        raise SystemExit('native_next: no room for a piece of %d bytes' % len(data))
    desc = {}
    for name, (col, pat, spr) in sorted(ev.items(), key=lambda x: -sum(len(t) for t in x[1])):
        desc[name] = [place(piece(t, nm, sz)) if t else None for t, nm, sz in ((col, 96, 8), (pat, 96, 8), (spr, 8, 32))]
    dat = b''.join(bytes(p) + bytes(0x2000 - len(p)) for p in pages)
    open(os.path.join(HERE, 'native_next.dat'), 'wb').write(dat)
    _, fix = stage_files()
    def d(x): return '    db 0xFF\n    dw 0' if x is None else '    db %d\n    dw 0x%04X' % x
    tab = ['; generated by native_next.py: the Next\'s graphics loads (do not edit)', 'nxl_tables:']
    for name in ('title', 'prestage', 'gameover', 'marcador', 'ending'):
        tab += ['nxl_%s_d:' % name] + [d(x) for x in desc[name]]
    tab.append('nxl_bigcore_tab:   ; stages 1-6')
    for n in range(1, 7): tab += [d(x) for x in desc['bigcore%d' % n]]
    tab.append('nxl_bonus_tab:     ; stages 10-12: characters whose colours differ from stage 9\'s (count, then index and 8 bytes each)')
    for n in (10, 11, 12):
        tab.append('    db %d' % len(fix[n]))
        for k, b in fix[n].items():
            tab += ['    dw 0x%04X' % k, '    db ' + ','.join('0x%02X' % x for x in b)]
    open(os.path.join(HERE, 'native_tables_next.asm'), 'w').write('\n'.join(tab) + '\n')
    print('native_next: %d bytes in %d pieces, pages %d-%d (%s)' % (sum(len(p) for p in pages), len(where), NX_PAGE,
          NX_PAGE + NX_PAGES - 1, ', '.join('%d' % len(p) for p in pages)))

if __name__ == '__main__':
    main()
