"""The 48K demo's beeper effects: writes z48_sfx.asm.

Konami's sound codes (the A of pide_sonido, 0:49E9; the disassembly's
comments) and what the 48K plays for each.  An effect is a list of frames;
each frame the interrupt plays one burst on the beeper (z48_stars.asm), a
tone sweeping or noise, for a few thousand T-states (frames below).  Codes not listed are silent; music (0x16 up) stays silent
too, but for the few that stand for events (the ship's death, the Big
Core's end, game over).
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
# A frame of an effect: (period, delta, budget, noise).  The beeper's
# half-cycles last 16 * period + 38 T-states; the period moves by delta at
# each half-cycle (a sweep within the frame); half-cycles go on to about
# `budget` T-states.  Noise: a 16-bit LFSR decides each half-cycle whether
# the speaker moves, `period` setting how fast it is clocked (low: hiss,
# high: rumble).
def T(*frames): return [(p, d, b, False) for p, d, b in frames]
def N(*frames): return [(p, d, b, True) for p, d, b in frames]

# name: (priority, frames)
EFFECTS = {
    'shot':     (1, T((30, 3, 16000))),                     # pew: about 3 kHz down to 1
    'laser':    (1, T((20, 2, 9000))),
    'hit':      (2, N((4, 0, 2500))),
    'pop':      (3, N((6, 0, 9000), (12, 0, 8000))),
    'bang':     (4, N((6, 0, 12000), (10, 0, 12000), (14, 0, 11000), (20, 0, 10000))),
    'capsule':  (5, T((70, -1, 20000), (45, -1, 20000))),
    'powerup':  (6, T((100, -2, 20000), (70, -1, 20000), (45, -1, 20000))),
    'bomb':     (7, N(*[(p, 0, 14000) for p in range(4, 44, 4)])),
    'oneup':    (7, T(*[(p, 0, 15000) for p in (40, 30, 40, 30, 22, 16)])),
    'death':    (9, N(*[(p, 0, 15000) for p in range(6, 86, 4)])),
    'bigbang':  (9, N(*[(p, 0, 15000) for p in range(4, 64, 2)])),
    'gameover': (9, T(*[(p, 0, 25000) for p in (40, 40, 50, 50, 60, 60, 80, 80, 100, 100)])),
    'start':    (8, T((80, 0, 20000), (60, 0, 20000), (45, 0, 20000), (30, -1, 20000))),
}

CODES = {
    0x01: 'shot', 0x02: 'shot',                     # the shot, the double
    0x03: 'laser',
    0x06: 'hit',                                    # a hit that does not kill
    0x07: 'pop', 0x08: 'pop', 0x09: 'pop', 0x0A: 'pop', 0x0B: 'pop', 0x0C: 'pop', 0x0D: 'pop',   # enemies
    0x0E: 'bang', 0x0F: 'bang',                     # a big piece, a wall
    0x10: 'capsule',
    0x11: 'oneup', 0x15: 'oneup',                   # a ship picked up, a ship given
    0x12: 'bomb',
    0x14: 'powerup',                                # the meter's choice taken
    0x32: 'start',                                  # stage 1's arrival
    0x38: 'bigbang', 0x3B: 'bigbang',               # the Big Core's end
    0x47: 'death',                                  # la_nave_ha_muerto
    0xCA & 0x7F: 'gameover',                        # (0xCA: the game's end)
}

def main():
    names = list(EFFECTS)
    out = ['; generated by z48_sfx.py: the 48K demo\'s beeper effects', '',
           'z48_sfx_code:                   ; Konami\'s sound code (0-7F) -> effect (0: none)']
    tab = [0] * 128
    for c, n in CODES.items(): tab[c] = names.index(n) + 1
    out += ['    db ' + ','.join('%d' % x for x in tab[i:i + 16]) for i in range(0, 128, 16)]
    out.append('z48_sfx_eff:                    ; per effect: its frames, its priority')
    for n in names:
        out.append('    dw z48_fx_%s' % n)
        out.append('    db %d' % EFFECTS[n][0])
    for n in names:
        out.append('z48_fx_%s:                   ; period, half-cycles (bit 7: noise), delta' % n)
        for p, d, budget, nz in EFFECTS[n][1]:
            count, t, q = 0, 0, p
            while count < 127 and 1 <= q <= 255 and t + 16 * q + 38 <= budget:
                t += 16 * q + 38; q += d; count += 1
            assert count and 1 <= p + d * (count - 1) <= 255
            out.append('    db %d,%d,%d' % (p, count | (0x80 if nz else 0), d & 0xFF))
        out.append('    db 0')
    open(os.path.join(HERE, 'z48_sfx.asm'), 'w').write('\n'.join(out) + '\n')
    print('z48_sfx.asm: %d effects, %d codes' % (len(names), len(CODES)))

if __name__ == '__main__':
    main()
