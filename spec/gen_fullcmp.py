"""Write fullcmp_gen.asm: the full comparison of Konami's 704-cell map with
name_shadow (after the big copies and the scroll's column shift, and every
64 ticks).

Each cell: equal falls through to the next; a changed one is copied and
marked in C (redraw) in line, as the comparison it replaces did.  Only when
the new tile may be empty (0) or a star (F6/F7) does an out-of-line block
look closer: B marks cells that are stars now, and a cell that went between
empty and a star both ways is moved from C to IXH when star_ok says the
three tiles differ only in row 0 and the attribute (render's draw_stars then
redraws the stars from lists).  The old tile waits in A' for that block.
IXL counts the 88 groups up from 256-88; full_grp takes each group to the
bitmaps."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
out = []
w = out.append
w('; Generated by gen_fullcmp.py: do not edit.')
w("; HL = Konami's map (ED00+KRAM), DE = name_shadow; both advance 704 cells.")
w('full_cmp:')
w("    ex af,af'")
w('    push af')
w('    ld ixl,256-88')
w('    jr .group')
# A changed cell's work is out of line (0.109), so an unchanged one, the
# usual case, falls through its jr nz: cells 0-3 jump back to blocks before
# the loop, cells 4-7 forward to blocks after it, all within jr range.
def changed(n):
    w('.c%d:' % n)
    w("    ex af,af'                   ; the old tile")
    w('    ld a,(hl)')
    w('    ld (de),a')
    w('    set %d,c' % n)
    w('    add a,10                    ; 0, F6, F7 (and F8, F9, FE, FF, 01) -> Z')
    w('    and 0xf4')
    w('    call z,.s%d' % n)
    w('    jr .b%d' % n)
for n in range(4):
    changed(n)
w('.group:')
w('    ld bc,0')
w('    ld ixh,b')
for n in range(8):
    w('    ld a,(de)')
    w('    cp (hl)')
    w('    jr nz,.c%d' % n)
    w('.b%d:' % n)
    w('    inc l')
    w('    inc e')
w('    jr nz,.np')
w('    inc h')
w('    inc d')
w('.np:')
w('    ld a,c')
w('    or ixh')
w('    call nz,full_grp')
w('    inc ixl')
w('    jp nz,.group')
w('    pop af')
w("    ex af,af'")
w('    ret')
for n in range(4, 8):
    changed(n)
for n in range(8):
    b = 1 << n
    w('.s%d:' % n)                         # new may be empty or a star; A' = old
    w('    ld a,(hl)')
    w('    or a')
    w('    jr z,.z%d' % n)
    w('    sub 0xf6')
    w('    cp 2')
    w('    ret nc')
    w('    set %d,b' % n)                  # a star now
    w("    ex af,af'")
    w('    or a')
    w('    jr z,.l%d' % n)
    w('    sub 0xf6')
    w('    cp 2')
    w('    ret nc')
    w('.l%d:' % n)                         # empty <-> star: left to draw_stars
    w('    ld a,(star_ok)')
    w('    or a')
    w('    ret z')
    w('    res %d,c' % n)
    w('    ld a,ixh')
    w('    or %d' % b)
    w('    ld ixh,a')
    w('    ret')
    w('.z%d:' % n)                         # empty now: was it a star?
    w("    ex af,af'")
    w('    sub 0xf6')
    w('    cp 2')
    w('    jr c,.l%d' % n)
    w('    ret')
w('; The group (cells IXL - (256-88)) to dirty0/dirty1 and star_cells.')
w('full_grp:')
w('    push hl')
w('    ld a,ixl')
w('    sub 256-88')
w('    ld l,a')
w('    ld h,dirty0>>8')
w('    ld a,c')
w('    or a')
w('    jr z,.nod')
w('    or (hl)')
w('    ld (hl),a')
w('    set 7,l')
w('    ld a,c')
w('    or (hl)')
w('    ld (hl),a')
w('    res 7,l')
w('.nod:')
w('    ld a,l')
w('    add a,star_cells&0xff')
w('    ld l,a')
w('    ld h,star_cells>>8')
w('    ld a,c')
w('    or ixh')
w('    cpl')
w('    and (hl)')
w('    or b')
w('    cp (hl)')
w('    ld (hl),a')
w('    jr nz,.stars')
w('    ld a,b                          ; a star here changed tile, or moved: new lists')
w('    or ixh')
w('    jr z,.same')
w('.stars:')
w('    ld a,1')
w('    ld (star_dirty),a')
w('    ld a,ixh')
w('    or a')
w('    ld a,3')
w('    jr z,.listed')
w('    ld (stars_moved),a              ; stars moved without a redraw: draw_stars')
w('    jr .same')
w('.listed:')
w('    ld (stars_listed),a             ; only the drawn lists need them')
w('.same:')
w('    pop hl')
w('    ret')
open(os.path.join(HERE, 'fullcmp_gen.asm'), 'w').write('\n'.join(out) + '\n')
